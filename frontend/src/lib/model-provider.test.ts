import { describe, it, expect, vi } from 'vitest';
import { MambaModelProvider } from './model-provider';

// ---------------------------------------------------------------------------
// Mock the API so the browser-LoRA tests can prove they make no network calls
// ---------------------------------------------------------------------------

vi.mock('./api', () => ({
  downloadDataset: vi.fn().mockResolvedValue(''),
  uploadArtifact: vi.fn().mockResolvedValue({ r2Key: 'adapters/test.bin' }),
  updateTrainingJob: vi.fn().mockResolvedValue(undefined),
  streamTrainingLogs: vi.fn().mockResolvedValue(undefined),
}));

import { WebGPUTrainer, type BrowserLoRAArtifact, type TrainingStep, type WebGPUTrainerOptions } from './webgpu-trainer';
import { EvermindModelPackage } from '@seanhogg/builderforce-memory-engine';

// ---------------------------------------------------------------------------
// MambaModelProvider
// ---------------------------------------------------------------------------

describe('MambaModelProvider', () => {
  it('has correct identity properties', () => {
    const provider = new MambaModelProvider();
    expect(provider.id).toBe('mamba');
    expect(provider.name).toBe('Mamba (On-Device WebGPU)');
    expect(provider.isLocal).toBe(true);
  });

  it('is not ready before init()', () => {
    const provider = new MambaModelProvider();
    expect(provider.isReady()).toBe(false);
  });

  it('gracefully handles missing @seanhogg/builderforce-memory-engine at init()', async () => {
    // In jsdom there is no navigator.gpu so @seanhogg/builderforce-memory-engine will throw
    const provider = new MambaModelProvider();
    // Should not throw even if the dynamic import fails
    await expect(provider.init()).resolves.toBeUndefined();
    expect(provider.isReady()).toBe(false);
  });

  it('returns a fallback message when not ready', async () => {
    const provider = new MambaModelProvider();
    const result = await provider.generate('hello');
    expect(result).toContain('not ready');
  });

  it('stream() falls back gracefully when not ready', async () => {
    const tokens: string[] = [];
    const provider = new MambaModelProvider();
    const result = await provider.stream('hello', undefined, (t) => tokens.push(t));
    expect(result).toContain('not ready');
    // The fallback message is word-streamed so at least one token is emitted
    expect(tokens.length).toBeGreaterThan(0);
    expect(tokens.join('').trim()).toContain('not ready');
  });

  it('train() throws when not ready', async () => {
    const provider = new MambaModelProvider();
    await expect(provider.train('some code')).rejects.toThrow('Provider not ready');
  });

  it('exportTrainedWeights() throws when not ready (no placeholder bytes)', async () => {
    const provider = new MambaModelProvider();
    await expect(provider.exportTrainedWeights()).rejects.toThrow('Provider not ready');
  });

  it('train() delegates to the REAL MambaTrainer.train (no synthetic loss)', async () => {
    const provider = new MambaModelProvider();
    // White-box: simulate a ready provider with a stub trainer that records the call.
    const realLosses = [2.31, 1.74, 1.12];
    const trainSpy = vi.fn().mockResolvedValue(realLosses);
    (provider as any)._ready = true;
    // A ready provider holds the full tokenizer + model + trainer triad. Stub all
    // three: `ensureModelForCorpus` only short-circuits when every one is present,
    // and otherwise falls through to building a real engine model (which throws
    // in jsdom, where there is no WebGPU).
    (provider as any).tokenizer = { vocabSize: 256 };
    (provider as any).model = {};
    (provider as any).trainer = { train: trainSpy };

    const epochCb = vi.fn();
    const losses = await provider.train('print("hi")', {
      learningRate: 5e-4,
      epochs: 3,
      onEpochEnd: epochCb,
    });

    // The returned losses are exactly what the real trainer produced — not
    // generated by Math.exp / Math.random in this layer.
    expect(losses).toBe(realLosses);
    expect(trainSpy).toHaveBeenCalledOnce();
    const [text, opts] = trainSpy.mock.calls[0] as [string, Record<string, unknown>];
    expect(text).toBe('print("hi")');
    expect(opts.learningRate).toBe(5e-4);
    expect(opts.epochs).toBe(3);
    expect(opts.onEpochEnd).toBe(epochCb);
  });

  it('exportTrainedWeights() returns REAL serialised weights from the model', async () => {
    const provider = new MambaModelProvider();
    const realBuffer = new ArrayBuffer(128);
    const exportSpy = vi.fn().mockResolvedValue(realBuffer);
    (provider as any)._ready = true;
    (provider as any).model = { exportWeights: exportSpy };

    const out = await provider.exportTrainedWeights({ fp16: true });
    expect(out).toBe(realBuffer);
    expect(exportSpy).toHaveBeenCalledWith({ fp16: true });
  });

  it('dispose() marks the provider as not ready', () => {
    const provider = new MambaModelProvider();
    // Simulate readiness by forcing the internal flag (white-box test)
    (provider as any)._ready = true;
    expect(provider.isReady()).toBe(true);
    provider.dispose();
    expect(provider.isReady()).toBe(false);
  });

  it('accepts custom config', () => {
    const provider = new MambaModelProvider({ dModel: 256, numLayers: 4, wsla: true });
    const cfg = (provider as any).config;
    expect(cfg.dModel).toBe(256);
    expect(cfg.numLayers).toBe(4);
    expect(cfg.wsla).toBe(true);
  });
});

// ---------------------------------------------------------------------------
// Browser LoRA — real frozen-base adapter training and portable artifacts
// ---------------------------------------------------------------------------

describe('WebGPUTrainer (exact browser LoRA)', () => {
  function makeTrainer(overrides: Partial<WebGPUTrainerOptions> = {}) {
    const logs: string[] = [];
    const trainer = new WebGPUTrainer({
      modelId: 'evermind-browser-test',
      workerUrl: 'http://localhost',
      projectId: 'proj-1',
      onLog: (m) => logs.push(m),
      onStep: () => {},
      onEpochEnd: () => {},
      onComplete: () => {},
      onError: () => {},
      ...overrides,
    });
    return { trainer, logs };
  }

  it('initialises the exact CPU path when WebGPU is unavailable', async () => {
    const { trainer, logs } = makeTrainer();
    await expect(trainer.init()).resolves.toBeUndefined();
    expect(logs.join('\n')).toMatch(/exact-gradient browser LoRA/i);
  });

  it('train() refuses to run before a successful init() (no synthetic loop)', async () => {
    const { trainer } = makeTrainer();
    await expect(
      trainer.train(
        {
          epochs: 2,
          batchSize: 4,
          learningRate: 1e-4,
          gradientAccumulationSteps: 1,
          precision: 'float16',
          loraConfig: { rank: 8, alpha: 16, targetModules: ['q_proj'] },
        },
        ['example'],
      ),
    ).rejects.toThrow(/not initialised/i);
  });

  it('trains real LoRA matrices locally and emits a valid safetensors adapter without network calls', async () => {
    const artifacts: BrowserLoRAArtifact[] = [];
    let completedKey = '';
    const steps: TrainingStep[] = [];
    const { trainer } = makeTrainer({
      dataMode: 'local-only',
      modelConfig: { dModel: 8, numLayers: 1, hiddenDim: 16, numExperts: 2, topK: 1 },
      onStep: (step) => steps.push(step),
      onArtifact: (artifact) => artifacts.push(artifact),
      onComplete: (key) => { completedKey = key; },
    });
    await trainer.init();
    await trainer.train(
      {
        epochs: 1,
        batchSize: 1,
        learningRate: 1e-3,
        gradientAccumulationSteps: 1,
        precision: 'float16',
        loraConfig: { rank: 2, alpha: 4, targetModules: ['embed_tokens'] },
      },
      ['hello browser adapter', 'hello private training'],
    );

    expect(steps).toHaveLength(1);
    expect(Number.isFinite(steps[0]!.loss)).toBe(true);
    expect(artifacts).toHaveLength(1);
    expect(artifacts[0]!.filename).toMatch(/\.safetensors$/);
    const view = new DataView(artifacts[0]!.bytes);
    const headerLength = Number(view.getBigUint64(0, true));
    const header = JSON.parse(new TextDecoder().decode(new Uint8Array(artifacts[0]!.bytes, 8, headerLength)));
    expect(header.__metadata__.peft_type).toBe('LORA');
    expect(header['base_model.model.embed_tokens.lora_A.weight'].shape).toEqual([2, 8]);
    expect(header['base_model.model.embed_tokens.lora_B.weight'].shape[1]).toBe(2);
    const runtimePackage = EvermindModelPackage.fromBlob(artifacts[0]!.evermindPackage);
    expect(runtimePackage.validate()).toEqual({ ok: true, errors: [] });
    expect(runtimePackage.loadLM().config.vocabSize).toBe(Object.keys(artifacts[0]!.tokenizer.vocab).length);
    const api = await import('./api');
    expect(api.downloadDataset).not.toHaveBeenCalled();
    expect(api.uploadArtifact).not.toHaveBeenCalled();
    expect(api.updateTrainingJob).not.toHaveBeenCalled();
    expect(completedKey).toMatch(/^local:\/\//);
  });

  it('source contains no synthetic Math.exp / Math.random loss generation', async () => {
    // Guard against regressions reintroducing the fake loss curve.
    const fs = await import('node:fs');
    const url = await import('node:url');
    const path = await import('node:path');
    const here = path.dirname(url.fileURLToPath(import.meta.url));
    const src = fs.readFileSync(path.join(here, 'webgpu-trainer.ts'), 'utf8');
    expect(src).not.toMatch(/Math\.exp/);
    expect(src).not.toMatch(/Math\.random/);
    // The old "prove GPU writing works" buffer hack must be gone.
    expect(src).not.toMatch(/prove GPU/i);
  });
});
