#!/usr/bin/env node
/**
 * Bundle the pure-Python `torch` (and `peft` shim) package under `python/` into
 * `src/pyodide/python-files.ts` (path → source text), so every consumer — any
 * bundler, tsc, a Worker — gets the files from a plain TS import with no
 * loader plugin or runtime fetch. `python/` is the source of truth;
 * `test/pyodide-python-files.test.ts` fails when the generated module is stale.
 *
 *   node scripts/gen-python-files.mjs          # regenerate
 *   node scripts/gen-python-files.mjs --check  # exit 1 when stale
 */
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, relative, sep } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const pythonDir = join(root, "python");
const outFile = join(root, "src", "pyodide", "python-files.ts");

/** Every `.py` file under `python/`, as [posix relative path, text], sorted by path. */
export function collectPythonFiles(dir = pythonDir) {
  const files = [];
  const walk = (current) => {
    for (const entry of readdirSync(current, { withFileTypes: true })) {
      const full = join(current, entry.name);
      if (entry.isDirectory()) {
        if (entry.name !== "__pycache__") walk(full);
      } else if (entry.name.endsWith(".py")) {
        files.push([relative(dir, full).split(sep).join("/"), readFileSync(full, "utf8").replace(/\r\n/g, "\n")]);
      }
    }
  };
  walk(dir);
  return files.sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0));
}

export function renderPythonFilesModule(files = collectPythonFiles()) {
  const body = files.map(([path, text]) => `  ${JSON.stringify(path)}: ${JSON.stringify(text)},`).join("\n");
  return [
    "// GENERATED by scripts/gen-python-files.mjs from python/ — do not edit; run `pnpm gen:python`.",
    "/** The Python `torch` package (and the `peft` shim), path → source. */",
    "export const PYTHON_FILES: Readonly<Record<string, string>> = {",
    body,
    "};",
    "",
  ].join("\n");
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const rendered = renderPythonFilesModule();
  if (process.argv.includes("--check")) {
    let current = "";
    try {
      current = readFileSync(outFile, "utf8");
    } catch {
      // missing counts as stale
    }
    if (current.replace(/\r\n/g, "\n") !== rendered) {
      console.error("src/pyodide/python-files.ts is stale: run `pnpm gen:python`");
      process.exit(1);
    }
  } else {
    writeFileSync(outFile, rendered);
    console.log(`wrote ${relative(root, outFile)}`);
  }
}
