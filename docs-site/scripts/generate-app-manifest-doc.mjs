/**
 * Generates src/content/docs/reference/app-manifest.md from the runtime's published JSON Schema
 * (`APP_MANIFEST_SCHEMA_V1`), so the page can never drift from what the parser accepts.
 * Run: node scripts/generate-app-manifest-doc.mjs   (after `pnpm install` in the repo root's api/).
 */
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const coreManifest = join(here, '../../api/node_modules/@seanhogg/builderforce-webcontainers-core/dist/manifest/index.js');
const { APP_MANIFEST_SCHEMA_V1: schema } = await import(pathToFileURL(coreManifest).href);

const cell = (text) => String(text ?? '').replace(/\|/g, '\|').replace(/\s*\n\s*/g, ' ');
const refName = (node) => node.$ref?.replace('#/$defs/', '');

/** A short type description of one property schema. */
function typeOf(node) {
  if (!node || typeof node !== 'object') return '';
  if (node.$ref) return `[${refName(node)}](#${refName(node).toLowerCase()})`;
  if (node.const !== undefined) return `\`${JSON.stringify(node.const)}\``;
  if (node.enum) return node.enum.map((value) => `\`${value}\``).join(' \| ');
  if (node.oneOf || node.anyOf) return (node.oneOf ?? node.anyOf).map(typeOf).join(' \| ');
  if (node.type === 'array') return `array of ${typeOf(node.items) || 'any'}`;
  if (node.type === 'object' && node.additionalProperties && typeof node.additionalProperties === 'object' && !node.properties) {
    return `map of ${typeOf(node.additionalProperties) || 'any'}`;
  }
  const type = Array.isArray(node.type) ? node.type.join(' \| ') : node.type ?? '';
  return node.pattern ? `${type} (\`${node.pattern}\`)` : type;
}

function table(node) {
  const properties = node.properties ?? {};
  const required = new Set(node.required ?? []);
  const rows = Object.entries(properties).map(
    ([name, value]) => `| \`${name}\` | ${cell(typeOf(value))} | ${required.has(name) ? 'yes' : 'no'} | ${cell(value.description)} |`,
  );
  return rows.length === 0 ? '_No fixed fields._\n' : ['| Field | Type | Required | Notes |', '| --- | --- | --- | --- |', ...rows, ''].join('\n');
}

const sections = [
  '---',
  'title: App manifest (builderforce.json)',
  'description: Every field of the Builderforce app manifest v1, generated from its JSON Schema.',
  '---',
  '',
  '<!-- Generated by docs-site/scripts/generate-app-manifest-doc.mjs from APP_MANIFEST_SCHEMA_V1. Do not edit by hand. -->',
  '',
  '# App manifest (`builderforce.json`)',
  '',
  `Schema: \`${schema.$id}\`. This page is generated from the schema the runtime validates against; the parser (\`parseManifest\`) is the authority for references between entries.`,
  '',
  '## Top level',
  '',
  table(schema),
];
for (const [name, definition] of Object.entries(schema.$defs ?? {})) {
  sections.push(`## ${name}`, '', definition.description ? `${definition.description}\n` : '', table(definition));
}
writeFileSync(join(here, '../src/content/docs/reference/app-manifest.md'), `${sections.join('\n')}\n`);
