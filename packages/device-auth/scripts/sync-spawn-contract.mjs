import { access, mkdir, readFile, writeFile } from 'node:fs/promises';
import { EDITOR_GATEWAY_BASE } from '../src/platformOrigins.ts';
import { TENANT_SESSION_TTL_SECONDS, WORKSPACE_TOKEN_PATH } from '../src/tenantSessionContract.ts';

// Spawn vendors the wire constants and fixture so it builds from a standalone checkout.
const fixture = new URL('../fixtures/gateway-contract.json', import.meta.url);
const crate = new URL('../../../../builderforce-spawn/crates/bf-cloud/', import.meta.url);
await access(new URL('Cargo.toml', crate));
const constants = `// Generated by Builderforce.ai/packages/device-auth/scripts/sync-spawn-contract.mjs.
pub(crate) const TENANT_SESSION_TTL_SECONDS: u64 = ${TENANT_SESSION_TTL_SECONDS};
pub(crate) const EDITOR_GATEWAY_BASE: &str = ${JSON.stringify(EDITOR_GATEWAY_BASE)};
const WORKSPACE_TOKEN_PATH: &str = ${JSON.stringify(WORKSPACE_TOKEN_PATH)};
`;
const outputs = [
  ['fixtures/gateway-contract.json', (await readFile(fixture, 'utf8')).replaceAll('\r\n', '\n')],
  ['src/gateway_contract.generated.rs', constants],
];
const check = process.argv.includes('--check');
if (!check) await mkdir(new URL('fixtures/', crate), { recursive: true });
for (const [file, expected] of outputs) {
  const destination = new URL(file, crate);
  if (check) {
    const actual = (await readFile(destination, 'utf8')).replaceAll('\r\n', '\n');
    if (actual !== expected) throw new Error(`${file} has drifted. Run sync-spawn-contract.mjs to regenerate it.`);
  } else {
    await writeFile(destination, expected);
  }
}
