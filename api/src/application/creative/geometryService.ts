/**
 * Geometry generation — turning a brief into a real drawing or a real solid.
 *
 * A CAD or 3D brief was previously honoured by a parameterised primitive built in
 * the browser: the file was valid and portable, but it described a fixed plate or
 * a fixed box rather than anything the prompt asked for. This module closes that
 * gap in the only way that is honest for geometry: a model chooses the SHAPE — the
 * outline, the features, the solids and their dimensions — under a strict schema,
 * and this module evaluates that shape deterministically into DXF or STL.
 *
 * The split matters. Asking a model to emit DXF or STL text directly produces
 * files that are plausible and frequently unopenable — an unclosed polyline, a
 * facet with two vertices, a normal that points into the solid. Asking it for a
 * bounded parametric spec instead means every file this emits is generated by code
 * that can only produce closed, well-formed geometry, while the shape is still the
 * one the brief described.
 *
 * Everything below the model call is pure: spec in, geometry text out. It runs in
 * a test with no network and no key.
 */

/* ---------- the spec a model is allowed to author ---------- */

export interface CadProfileSpec {
  /** Closed outer boundary, in millimetres, counter-clockwise. */
  outline: Array<{ x: number; y: number }>;
  /** Bores and clearance holes cut from the profile. */
  holes?: Array<{ x: number; y: number; r: number }>;
  /** Open construction lines — fold lines, centrelines, cut paths. */
  lines?: Array<{ x1: number; y1: number; x2: number; y2: number }>;
  /** What the drawing is, in the model's own words. Kept for the deliverable. */
  summary?: string;
}

export type SolidSpec =
  | { type: 'box'; x: number; y: number; z: number; width: number; depth: number; height: number }
  | { type: 'cylinder'; x: number; y: number; z: number; radius: number; height: number }
  | { type: 'sphere'; x: number; y: number; z: number; radius: number };

export interface Model3dSpec {
  solids: SolidSpec[];
  summary?: string;
}

/** Tessellation density. Fine enough to read as round, coarse enough to stay small. */
const ARC_SEGMENTS = 32;
const SPHERE_BANDS = 16;
/** A model that runs away with the spec must not turn into a 40 MB export. */
const MAX_SOLIDS = 48;
const MAX_OUTLINE_POINTS = 512;

const CAD_SCHEMA = {
  type: 'object',
  additionalProperties: false,
  required: ['outline', 'summary'],
  properties: {
    outline: {
      type: 'array',
      minItems: 3,
      items: {
        type: 'object',
        additionalProperties: false,
        required: ['x', 'y'],
        properties: { x: { type: 'number' }, y: { type: 'number' } },
      },
    },
    holes: {
      type: 'array',
      items: {
        type: 'object',
        additionalProperties: false,
        required: ['x', 'y', 'r'],
        properties: { x: { type: 'number' }, y: { type: 'number' }, r: { type: 'number' } },
      },
    },
    lines: {
      type: 'array',
      items: {
        type: 'object',
        additionalProperties: false,
        required: ['x1', 'y1', 'x2', 'y2'],
        properties: { x1: { type: 'number' }, y1: { type: 'number' }, x2: { type: 'number' }, y2: { type: 'number' } },
      },
    },
    summary: { type: 'string' },
  },
} as const;

const MODEL3D_SCHEMA = {
  type: 'object',
  additionalProperties: false,
  required: ['solids', 'summary'],
  properties: {
    solids: {
      type: 'array',
      minItems: 1,
      items: {
        type: 'object',
        additionalProperties: false,
        required: ['type', 'x', 'y', 'z'],
        properties: {
          type: { type: 'string', enum: ['box', 'cylinder', 'sphere'] },
          x: { type: 'number' }, y: { type: 'number' }, z: { type: 'number' },
          width: { type: 'number' }, depth: { type: 'number' }, height: { type: 'number' },
          radius: { type: 'number' },
        },
      },
    },
    summary: { type: 'string' },
  },
} as const;

