/**
 * The `gcp-cloudrun` hosting adapter — the same handlers, running in the
 * customer's own Google Cloud project on Cloud Run.
 *
 * ── WHY CLOUD RUN AND NOT CLOUD FUNCTIONS ───────────────────────────────────
 * Cloud Run takes a container and gives back a URL, and the container is a
 * three-line Dockerfile over a plain Node server. Cloud Functions would need the
 * functions-framework as a dependency and a per-function entrypoint contract,
 * which buys nothing here: the engine is already a single request handler. It
 * also means the same image runs unchanged on any container host the customer
 * moves to later, which is the whole reason someone picks their own cloud.
 *
 * ── WHY THE URL IS REBUILT FROM FORWARDED HEADERS ───────────────────────────
 * Cloud Run terminates TLS and hands the container a plain HTTP request, so
 * `req.url` has no scheme and no public host. Twilio signs the URL it called
 * byte for byte, so a signature verified against `http://localhost:8080/sms`
 * fails every real request while looking exactly like a wrong auth token.
 */

