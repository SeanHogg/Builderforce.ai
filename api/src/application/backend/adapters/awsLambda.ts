/**
 * The `aws-lambda` hosting adapter — the same handlers, running in the
 * customer's own AWS account behind a Lambda Function URL.
 *
 * ── WHY AWS AT ALL ──────────────────────────────────────────────────────────
 * "It runs on our platform" is not an acceptable answer to a procurement
 * question. A business that has to demonstrate the system runs in ITS cloud —
 * for data residency, for an existing enterprise agreement, for a security
 * review that only knows how to audit one provider — could previously only be
 * told no. The hosting port already existed for exactly this; this is the
 * adapter it was shaped for.
 *
 * ── WHY A FUNCTION URL AND NOT API GATEWAY ──────────────────────────────────
 * A Function URL is one resource, needs no separate stage, no usage plan and no
 * second thing to misconfigure, and it hands the request through in the same
 * payload format API Gateway v2 uses — so the entrypoint below would not change
 * if a customer later fronts it with a gateway of their own.
 *
 * ── WHY AuthType: NONE ──────────────────────────────────────────────────────
 * IAM auth on the URL would be strictly worse than useless here: Twilio, Stripe
 * and Shopify cannot sign a SigV4 request, so the ONLY callers it would exclude
 * are the ones the system exists to serve. Authentication for these endpoints is
 * per-handler signature verification, which the engine performs and which no
 * amount of transport auth would replace. That is why `verify` has no default.
 */

