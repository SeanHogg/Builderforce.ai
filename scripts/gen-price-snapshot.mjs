#!/usr/bin/env node
/**
 * The bundled PRICE SNAPSHOT — `packages/model-catalog/src/generated/priceSnapshot.ts`.
 *
 * A VS Code chat prices its own calls on the device (PRD 36): offline, signed out, or for
 * the turns the platform never sees (a local model). It needs the per-token prices the
 * gateway's usage ledger prices from, and those come from OpenRouter's public models list
 * (`api/src/application/llm/modelCatalog.ts`). This script reads the SAME list and writes
 * it out as pure data, so a figure priced on the device and the ledger's figure for the
 * same model agree on the day of the release that shipped the snapshot.
 *
 *   node scripts/gen-price-snapshot.mjs           regenerate (keeps the old file if offline)
 *   node scripts/gen-price-snapshot.mjs --strict  fail when the catalog cannot be read
 *
 * Run by the extension's `vscode:prepublish`, so every release ships the prices of its
 * own day. Long-context tiers are NOT written here: the snapshot's book attaches them on
 * read (`withPriceTiers`), from the one tier table in `priceTiers.ts`.
 */
import { existsSync, mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const outFile = join(repoRoot, 'packages', 'model-catalog', 'src', 'generated', 'priceSnapshot.ts');
const OPENROUTER_MODELS_URL = 'https://openrouter.ai/api/v1/models';
const strict = process.argv.includes('--strict');

/** An OpenRouter pricing string → a finite, non-negative number (0 when absent). The
 *  same coercion the api's catalog normalizer applies. */
function num(value) {
  const n = typeof value === 'number' ? value : Number.parseFloat(String(value ?? ''));
  return Number.isFinite(n) && n > 0 ? n : 0;
}

async function readCatalog() {
  const headers = { accept: 'application/json' };
  if (process.env.OPENROUTER_API_KEY) headers.authorization = `Bearer ${process.env.OPENROUTER_API_KEY}`;
  const res = await fetch(OPENROUTER_MODELS_URL, { headers });
  if (!res.ok) throw new Error(`OpenRouter models request failed (${res.status})`);
  const json = await res.json();
  const rows = [];
  for (const model of Array.isArray(json?.data) ? json.data : []) {
    if (typeof model?.id !== 'string' || model.id === '') continue;
    rows.push([model.id, num(model.pricing?.prompt), num(model.pricing?.completion)]);
  }
  return rows.sort((a, b) => a[0].localeCompare(b[0]));
}

function render(rows, at) {
  const lines = rows.map(([id, input, output]) => `  ${JSON.stringify(id)}: [${input}, ${output}],`);
  return `/**
 * GENERATED by \`scripts/gen-price-snapshot.mjs\` — do not edit by hand.
 *
 * Per-token list prices (USD per token: [input, output]) from OpenRouter's public models
 * list, as of {@link PRICE_SNAPSHOT_AT}. Read through \`snapshotPriceBook()\`.
 */

export const PRICE_SNAPSHOT_AT = ${JSON.stringify(at)};

export const PRICE_SNAPSHOT: Readonly<Record<string, readonly [number, number]>> = {
${lines.join('\n')}
};
`;
}

try {
  const rows = await readCatalog();
  if (rows.length === 0) throw new Error('OpenRouter returned no models');
  mkdirSync(dirname(outFile), { recursive: true });
  writeFileSync(outFile, render(rows, new Date().toISOString()));
  console.log(`price snapshot: ${rows.length} models → ${outFile}`);
} catch (error) {
  const reason = error instanceof Error ? error.message : String(error);
  if (strict || !existsSync(outFile)) {
    console.error(`price snapshot: ${reason}`);
    process.exit(1);
  }
  console.warn(`price snapshot: ${reason} — keeping the snapshot already in the tree`);
}
